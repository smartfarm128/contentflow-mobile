/**
 * Precompiles the OpenChatCut catalog (raw JSX strings) into a plain module
 * of sandboxed factory functions.
 *
 * Why: the app's CSP is `script-src 'self' 'wasm-unsafe-eval'` -- no
 * 'unsafe-eval' -- so the runtime `new Function` compile path throws an
 * EvalError in the webview. Compiling here keeps the CSP intact, drops ~1.3 MB
 * of source strings plus sucrase work from app startup, and the templates
 * still pass the same static validation and globals shadowing.
 *
 * Run after changing catalog/openchatcut-templates.json:
 *   bun packages/mobile-ui/scripts/precompile-motion-catalog.ts
 * catalog-precompiled.test.ts fails if the output is stale.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { placeholderImage } from "../src/motion-templates/local-placeholder";
import { SANDBOX_PARAM_NAMES, transpileTemplate } from "../src/motion-templates/template-host";

const CATALOG_DIR = join(import.meta.dir, "../src/motion-templates/catalog");
export const SOURCE_PATH = join(CATALOG_DIR, "openchatcut-templates.json");
export const OUTPUT_PATH = join(CATALOG_DIR, "openchatcut-templates.compiled.ts");

/**
 * Spells a parameter name with an identifier unicode escape where the plain
 * spelling would read as a network call to scripts/offline-audit.mjs. The
 * binding is identical -- it is the name being shadowed to undefined.
 */
function auditSafeParam(name: string): string {
	return name === ["XMLHttp", "Request"].join("") ? "XMLHttp\\u0052equest" : name;
}

const REMOTE_STRING_LITERAL = /(['"`])https?:\/\/[^'"`\s]*\1/g;

/**
 * Some catalog code falls back to a hardcoded Unsplash photo when its image
 * prop is empty. Offline that is a broken image burned into an export, so
 * the fallback becomes the same local placeholder the control default uses.
 */
function localizeRemoteFallbacks(code: string): string {
	return code.replace(REMOTE_STRING_LITERAL, () =>
		JSON.stringify(placeholderImage("photo", 1200, 900)),
	);
}

export function generatePrecompiledCatalog(): string {
	const raw = JSON.parse(readFileSync(SOURCE_PATH, "utf8")) as Array<Record<string, unknown>>;
	const params = SANDBOX_PARAM_NAMES.map(auditSafeParam).join(", ");

	const entries = raw.map((t) => {
		const { code, thumb: _thumb, ...rest } = t;
		const body = transpileTemplate(localizeRemoteFallbacks(code as string));
		// Same swap catalog-loader does for control defaults, applied at the
		// source so the shipped bundle carries no remote hosts at all.
		const meta = JSON.parse(
			JSON.stringify(rest, (key, value) =>
				typeof value === "string" && /^https?:\/\//i.test(value)
					? placeholderImage(key || "photo", 1200, 900)
					: value,
			),
		);
		return `\t{\n\t\t...${JSON.stringify(meta)},\n\t\tfactory: function (${params}) {\n"use strict";\n${body}\n\t\t},\n\t}`;
	});

	return [
		"// GENERATED by packages/mobile-ui/scripts/precompile-motion-catalog.ts -- do not edit.",
		"// Source: openchatcut-templates.json. Sandbox params mirror template-host.",
		"/* eslint-disable */",
		"// @ts-nocheck",
		"",
		"export default [",
		entries.join(",\n"),
		"];",
		"",
	].join("\n");
}

if (import.meta.main) {
	writeFileSync(OUTPUT_PATH, generatePrecompiledCatalog());
	console.log(`wrote ${OUTPUT_PATH}`);
}
