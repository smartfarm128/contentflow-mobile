function wrapWithBackgroundToggle(Component: HtmlTemplateComponent): HtmlTemplateComponent {
  return function WrappedComponent(props) {
    const { values } = props;
    const showBackground = values.showBackground !== false;

    // 1. Prepare modified values
    const modifiedValues = { ...values };
    if (!showBackground) {
      // Unconditionally set background colors to transparent to override template defaults
      modifiedValues.backgroundColor = "rgba(0,0,0,0)";
      modifiedValues.bgColor = "rgba(0,0,0,0)";
      modifiedValues.bg = "rgba(0,0,0,0)";
      modifiedValues.bgGradientColor = "rgba(0,0,0,0)";
      modifiedValues.bgGradient = "none";
      modifiedValues.bgOpacity = 0;
    }

    // 2. Render the inner component
    const element = Component({ ...props, values: modifiedValues });

    // 3. Post-process to remove CSS backgrounds if showBackground is false
    if (!showBackground && element && React.isValidElement(element)) {
      const existingStyle = (element.props as any).style || {};
      const newStyle = {
        ...existingStyle,
        backgroundColor: "transparent",
        backgroundImage: "none",
      };
      return React.cloneElement(element, { style: newStyle } as any);
    }

    return element;
  };
}

